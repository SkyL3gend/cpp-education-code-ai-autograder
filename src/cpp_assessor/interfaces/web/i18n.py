def normalize_lang(value: str | None) -> str:
    return "en" if (value or "").lower().startswith("en") else DEFAULT_LANG


def translator(lang: str) -> Any:
    """返回模板里可调用的 ``t(key, **fmt)``；缺失键显式暴露，便于测试发现。"""

    def t(key: str, **fmt: Any) -> str:
        table = TEXTS.get(lang) or TEXTS[DEFAULT_LANG]
        text = table.get(key) or TEXTS[DEFAULT_LANG].get(key)
        if text is None:
            return f"⟦{key}⟧"
        return text.format(**fmt) if fmt else text

    return t


def label(kind: str, value: str | None) -> str:
    """把枚举代码渲染成 ``English · 中文``；未知代码原样返回。"""
    if not value:
        return "—"
    pair = _LABELS.get(kind, {}).get(str(value))
    if pair is None:
        return str(value)
    return f"{pair[0]} · {pair[1]}"


def verdict_label(value: str | None) -> str:
    return label("verdict", value)


def status_label(value: str | None) -> str:
    return label("assessment", value)


def comparison_label(value: str | None) -> str:
    return label("comparison", value)


def execution_label(value: str | None) -> str:
    return label("execution", value)


def termination_label(value: str | None) -> str:
    return label("termination", value)
